            <h2>1. Marco Normativo Aplicable</h2>
            <p>
                El tratamiento y almacenamiento de datos personales en esta plataforma se rige con estricto apego a las disposiciones de la <strong>Ley N° 19.628 sobre Protección de la Vida Privada</strong> de la República de Chile, sus modificaciones, y a los principios de proporcionalidad, finalidad, seguridad y confidencialidad reconocidos en la legislación nacional e internacional.
            </p>

            <h2>2. Información que Recopilamos</h2>
            <p>
                Para prestar los servicios de redacción, validación de identidad y suscripción electrónica de documentos, podemos recopilar los siguientes datos:
            </p>
            <ul>
                <li><strong>Datos de Identificación Personal:</strong> Nombres, apellidos, Rol Único Tributario (RUT / RUN), estado civil, profesión u oficio y domicilio legal.</li>
                <li><strong>Datos de Contacto y Notificación:</strong> Correo electrónico y número telefónico móvil (utilizado para el envío de enlaces de firma y confirmaciones vía WhatsApp y correo).</li>
                <li><strong>Información Específica del Trámite:</strong> Datos del bien inmueble (dirección, rol de avalúo), antecedentes laborales (sueldo, causales de finiquito), o términos acordados entre las partes.</li>
                <li><strong>Metadatos Técnicos y Evidencia Forense:</strong> Dirección IP, huella de tiempo (<em>timestamp</em>), identificador de navegador y hash criptográfico SHA-256 generado al momento de la firma para conformar la cadena de custodia legal.</li>
            </ul>

            <h2>3. Finalidad del Tratamiento de Datos</h2>
            <p>
                Los datos personales recopilados se destinan exclusivamente a los siguientes fines:
            </p>
            <ol>
                <li>Componer y redactar materialmente los contratos o declaraciones solicitadas por el usuario.</li>
                <li>Autenticar la identidad de los firmantes mediante factores de autenticación (OTP, ClaveÚnica o biometría).</li>
                <li>Emitir el certificado digital de firma y estampar el código QR de validación en el documento PDF.</li>
                <li>Custodiar el documento firmado en la bóveda digital y permitir la consulta en el verificador público mediante el código alfanumérico único.</li>
                <li>Prestar soporte operativo y remitir comprobantes tributarios (boleta o factura exenta/afecta).</li>
            </ol>

            <h2>4. Seguridad y Cifrado de la Información (Cloudflare R2)</h2>
            <p>
                Implementamos estándares de seguridad de nivel bancario e infraestructura de clase mundial:
            </p>
            <ul>
                <li><strong>Cifrado en Tránsito:</strong> Todas las comunicaciones entre el usuario y la Plataforma se transmiten mediante canales cifrados utilizando protocolos <strong>TLS 1.3 / SSL</strong> de 256 bits.</li>
                <li><strong>Cifrado en Reposo:</strong> Los documentos PDF firmados se resguardan en la bóveda criptográfica de <strong>Cloudflare R2</strong> con cifrado AES-256 de forma inmutable.</li>
                <li><strong>Integridad Criptográfica:</strong> Se genera un Hash SHA-256 único por archivo, impidiendo cualquier modificación o adulteración posterior sin que sea alertada por el validador.</li>
            </ul>

            <h2>5. Derechos del Titular de los Datos (ARCO)</h2>
            <p>
                Conforme al Artículo 12 de la Ley N° 19.628, los titulares de los datos tienen derecho a solicitar en cualquier momento el <strong>acceso, rectificación, cancelación u oposición</strong> de sus datos personales almacenados en nuestros registros no vinculados a contratos vigentes ya suscritos con terceros.
            </p>
            <p>
                Para ejercer estos derechos, el titular puede enviar una comunicación escrita dirigida al Oficial de Privacidad al correo electrónico: <a href="mailto:privacidad@sinnotario.cl" style="color:var(--primary); font-weight:700;">privacidad@sinnotario.cl</a>.
            </p>

            <h2>6. Uso de Cookies y Telemetría Anónima</h2>
            <p>
                La Plataforma utiliza cookies técnicas estrictamente necesarias para la sesión del usuario y la navegación fluida. Adicionalmente, cuenta con un sistema de telemetría propio, privado y no invasivo orientado a medir el rendimiento de los formularios y la tasa de éxito de los trámites, sin almacenar datos sensibles en perfiles de seguimiento comercial externos.
            </p>

            <h2>7. Modificaciones a la Política</h2>
            <p>
                Keystone Advisors SpA se reserva el derecho de modificar la presente Política de Privacidad para adecuarla a futuras reformas legislativas o mejoras tecnológicas. Toda modificación sustancial será notificada a través del portal con indicación clara de su fecha de entrada en vigencia.
            </p>
